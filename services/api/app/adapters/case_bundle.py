"""q_case as one Postgres round trip: the sb.case_bundle_v datasource view (zetaris/30_case.sql). Owner: nexus-2.

Why: q_case read six JDBC tables (crime + vehicles, statements, evidence, forensics, features). Each table is a
separate Spark JDBC scan, and each scan opens a pooled connection to Supabase (~1 s connect + TLS + auth, plus
~0.35 s per round trip from here), so a call cost 7-31 s live. This view does the joins inside Postgres with
correlated sub-selects, so Zetaris pushes `WHERE crime_id = ...` into one native query and makes one trip.

The output is q_case's contract (zetaris_queries_n1.CASE_COLUMNS), with:
- timestamps as ISO strings in city time with the UTC offset ("2026-10-14T19:40:00+05:30"), computed in
  Postgres from the city pack timezone ({{city:timezone}}, filled by register.py; D-004);
- jsonb and nested lists as JSON text (`::text`), since JDBC carries them as strings anyway;
- nested lists ordered by their id (statement_id, evidence_id, forensic_id; vehicles by role, plate).

zetaris_reader has no USAGE on the extensions schema, so nothing here calls PostGIS.
"""

from __future__ import annotations

TZ = "{{city:timezone}}"


def ist(col: str) -> str:
    """ISO-8601 local time with offset for a timestamptz column, in Postgres. Matches Spark's cast-to-string:
    fractional seconds only when non-zero, trailing zeros trimmed (".909", ".867853")."""
    local = f"({col} AT TIME ZONE '{TZ}')"
    off = f"({local} - ({col} AT TIME ZONE 'UTC'))"
    frac = (f"CASE WHEN date_part('microseconds', {local})::bigint % 1000000 = 0 THEN '' "
            f"ELSE '.' || rtrim(to_char({local}, 'US'), '0') END")
    return (f"CASE WHEN {col} IS NULL THEN NULL ELSE to_char({local}, 'YYYY-MM-DD\"T\"HH24:MI:SS') || {frac} || "
            f"CASE WHEN {off} < interval '0' THEN '-' || to_char(-{off}, 'HH24:MI') "
            f"ELSE '+' || to_char({off}, 'HH24:MI') END END")


def view_sql() -> str:
    return f"""SELECT c.crime_id, c.source, c.source_row_id, c.station_id, c.fir_no, c.category, c.sub_type,
  c.sections::text AS sections,
  {ist('c.occurred_from')} AS occurred_from,
  {ist('c.occurred_to')} AS occurred_to,
  {ist('c.reported_at')} AS reported_at,
  c.lat, c.lon, c.address, c.ward_no, c.h3_r9, c.h3_r8, c.geohash7, c.week, c.severity::int AS severity,
  c.property::text AS property, c.weapon, c.offenders_described::text AS offenders_described,
  c.victims::text AS victims, c.status, c.narrative, c.synthetic,
  coalesce((SELECT json_agg(json_build_object('role', v.role, 'type', v.vehicle_type, 'plate', v.plate_pattern,
      'make_model', v.make_model, 'colour', v.colour) ORDER BY v.role, v.plate_pattern)
    FROM public.crime_vehicles v WHERE v.crime_id = c.crime_id)::text, '[]') AS vehicles,
  coalesce((SELECT json_agg(json_build_object('statement_id', s.statement_id, 'witness_ref', s.witness_ref,
      'mode', s.mode, 'text', s.text, 'recorded_at', {ist('s.recorded_at')}) ORDER BY s.statement_id)
    FROM public.statements s WHERE s.crime_id = c.crime_id)::text, '[]') AS statements,
  coalesce((SELECT json_agg(json_build_object('evidence_id', e.evidence_id, 'kind', e.kind,
      'storage_path', e.storage_path, 'captured_at', {ist('e.captured_at')}, 'camera_id', e.camera_id,
      'vision', e.vision) ORDER BY e.evidence_id)
    FROM public.evidence_media e WHERE e.crime_id = c.crime_id)::text, '[]') AS evidence,
  coalesce((SELECT json_agg(json_build_object('forensic_id', f.forensic_id, 'kind', f.kind,
      'match_code', f.match_code) ORDER BY f.forensic_id)
    FROM public.forensics f WHERE f.crime_id = c.crime_id)::text, '[]') AS forensics,
  (SELECT json_build_object('extractor_version', cf.extractor_version, 'model', cf.model,
      'receipt_id', cf.receipt_id, 'mo', cf.mo, 'visual_tags', to_json(cf.visual_tags), 'entities', cf.entities,
      'confidence', cf.confidence, 'reviewed_by_officer', cf.reviewed_by IS NOT NULL)::text
    FROM public.crime_features cf WHERE cf.crime_id = c.crime_id
    ORDER BY cf.extractor_version DESC LIMIT 1) AS features
FROM public.crimes c"""


def case_file() -> str:
    head = """-- zetaris/30_case.sql · q_case in one Postgres round trip (perf). Owner: nexus-2.
-- GENERATED by `python -m app.adapters.case_bundle`; tests/engines/test_case_bundle.py checks it.
-- A native-SQL datasource view over sb: Zetaris pushes `WHERE crime_id = ...` into it (verified with EXPLAIN on
-- crime_features_v), so q_case becomes one JDBC trip instead of six. register.py fills {{city:timezone}}.
"""
    return head + "\nCREATE DATASOURCE VIEW case_bundle_v FROM sb AS " + " ".join(view_sql().split()) + ";\n"


# The Lightning text q_case switches to once sb.case_bundle_v is registered (PR B, after R12 + a live check).
def q_case_lightning(columns: tuple[str, ...]) -> str:
    return f"SELECT {', '.join(columns)} FROM sb.case_bundle_v WHERE crime_id = :crime_id"


if __name__ == "__main__":
    from pathlib import Path

    out = Path(__file__).resolve().parents[4] / "zetaris" / "30_case.sql"
    out.write_text(case_file(), encoding="utf-8", newline="\n")
    print(f"wrote {out}")
