"""Export the named POIs of the OSM reference set to the city pack as plain text, one name per line.

The Extractor's MO-tag address guard (WS2-25) strips named places from MO labels; agent code may not open a
database or DuckDB itself (R1), so it reads this generated list. Re-run after data/reference is rebuilt:

    python scripts/export_poi_names.py [city]
"""

from __future__ import annotations

import sys
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]


def main(city: str = "chennai") -> None:
    src = ROOT / "data" / "reference" / "osm_pois.parquet"
    out = ROOT / "cities" / city / "poi_names.txt"
    rows = duckdb.sql(
        f"SELECT DISTINCT trim(name) AS n FROM read_parquet('{src.as_posix()}') "
        "WHERE name IS NOT NULL AND trim(name) <> '' ORDER BY n"
    ).fetchall()
    header = "# Generated by scripts/export_poi_names.py from data/reference/osm_pois.parquet (OSM, ODbL). Do not edit.\n"
    out.write_text(header + "".join(f"{r[0]}\n" for r in rows), encoding="utf-8", newline="\n")
    print(f"{len(rows)} names -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main(*sys.argv[1:2])
